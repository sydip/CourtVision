export type PlayerRow = [
  name: string,
  pts: number,
  reb: number,
  ast: number,
  stl: number,
  blk: number,
  to: number,
  fg: string,
  tp: string,
  ft: string,
  pm: string,
];

export type TeamTotals = [
  fg: string,
  tp: string,
  ft: string,
  reb: number,
  ast: number,
  stl: number,
  blk: number,
  to: number,
  pf: number,
];

export type TeamBox = {
  q: number[];
  tot: TeamTotals;
  players: PlayerRow[];
};

export type Game = {
  n: number;
  date: string;
  loc?: string;
  ot?: boolean;
  note?: string;
  scores: Record<number, number>;
  winnerId: number;
  boxes?: Record<number, TeamBox>;
};

export type Participant = { id: number; seed?: number; wins: number };

export type Series = {
  round: string;
  top: Participant;
  bottom: Participant;
  winnerId: number;
  games: Game[];
};

