function game(
  n: number,
  date: string,
  winnerId: number,
  winnerScore: number,
  loserId: number,
  loserScore: number,
  extra?: Partial<Pick<Game, "loc" | "ot" | "boxes">>,
): Game {
  return {
    n,
    date,
    winnerId,
    scores: { [winnerId]: winnerScore, [loserId]: loserScore },
    ...extra,
  };
}

function bx(q: number[], tot: TeamTotals, players: PlayerRow[]): TeamBox {
  return { q, tot, players };
}

function playInGame(
  round: string,
  date: string,
  loc: string,
  winnerId: number,
  winnerScore: number,
  loserId: number,
  loserScore: number,
  boxes: Record<number, TeamBox>,
  ot = false,
): Series {
  return {
    round,
    top: { id: winnerId, wins: 1 },
    bottom: { id: loserId, wins: 0 },
    winnerId,
    games: [game(1, date, winnerId, winnerScore, loserId, loserScore, { loc, ot, boxes })],
  };
}

